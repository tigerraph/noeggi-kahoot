do $$
declare e record; got bigint; h text; v int; w int; x int; y int; i int := 0;
begin
  for e in select * from _noeggi_expected order by t loop
    i := i + 1;
    execute format('select count(*) from noeggi.%I', e.t) into got;
    if e.t = 'scores' then
      select md5(coalesce(string_agg(format('%L|%L|%L|%L|%L|%L|%L', id, name, score, correct, len, mode, created_at), E'\n' order by id), '')) into h from noeggi.scores;
    elsif e.t = 'players' then
      select md5(coalesce(string_agg(format('%L|%L|%L|%L|%L', token, name, collected, fp, updated_at), E'\n' order by token), '')) into h from noeggi.players;
    elsif e.t = 'feedback' then
      select md5(coalesce(string_agg(format('%L|%L|%L|%L|%L|%L|%L', id, qid, claim, name, token, lang, created_at), E'\n' order by id), '')) into h from noeggi.feedback;
    else
      select md5(coalesce(string_agg(format('%L|%L|%L|%L|%L', id, name, points, reason, created_at), E'\n' order by id), '')) into h from noeggi.bonus;
    end if;
    insert into _noeggi_check values (i, e.t || ': all rows copied', got = e.n and h = e.h,
