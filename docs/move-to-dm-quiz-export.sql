$IMPORT$-- Nöggi-Kahoot → dm-quiz project: step 2 of 2, the IMPORT
-- Generated by docs/move-to-dm-quiz-export.sql in the old project. Run it in the
-- dm-quiz project's SQL editor. Safe to run again (existing rows are kept).
--
-- One project, two apps, never mixed: everything of the wedding quiz lives in the
-- schema «noeggi» (same table and function names as before), DM stays in «public».
-- Only anon gets rights here, and only the ones the quiz uses; nothing in this
-- script reads or changes anything outside «noeggi». The quiz uses no Auth and no
-- Storage.
-- The API must expose the schema (Project Settings → API → Exposed schemas: add
-- noeggi), or the quiz gets «Invalid schema: noeggi».

create schema if not exists noeggi;
revoke all on schema noeggi from public;
grant usage on schema noeggi to anon;

-- ------------------------------------------------------------------ tables
create table if not exists noeggi.scores (
  id bigint generated always as identity primary key,
  name text not null check (char_length(name) between 1 and 14),
  score int not null check (score between 0 and 40000),
  correct int not null check (correct between 0 and 23),
  len int not null check (len in (10,23)),
  mode text not null check (mode in ('23','10','⚡10','👾10')),
  created_at timestamptz not null default now()
);
create table if not exists noeggi.players (
  token uuid primary key,
  name text not null check (char_length(name) between 1 and 14),
  collected jsonb not null default '[]',
  fp text,
  updated_at timestamptz not null default now()
);
create index if not exists players_fp_idx on noeggi.players (fp);
create table if not exists noeggi.feedback (
  id bigint generated always as identity primary key,
  qid text not null check (char_length(qid) between 1 and 40),
  claim text not null check (char_length(claim) between 1 and 200),
  name text check (char_length(name) between 1 and 14),
  token uuid,
  lang text check (lang in ('de','fr','en')),
  created_at timestamptz not null default now()
);
create table if not exists noeggi.bonus (
  id bigint generated always as identity primary key,
  name text not null check (char_length(name) between 1 and 14),
  points int not null check (points between -40000 and 40000),
  reason text,
  created_at timestamptz not null default now()
);

-- ------------------------------------------ access: the same as in the old project
-- scores: anon inserts and reads (the leaderboard). players: no direct access,
-- only through the functions below. feedback: anon inserts only. bonus: anon reads.
-- Table rights are granted explicitly (and nothing else), RLS on top as before.
revoke all on all tables in schema noeggi from public, anon, authenticated;
grant select, insert on noeggi.scores   to anon;
grant insert         on noeggi.feedback to anon;
grant select         on noeggi.bonus    to anon;
alter table noeggi.scores   enable row level security;
alter table noeggi.players  enable row level security;
alter table noeggi.feedback enable row level security;
alter table noeggi.bonus    enable row level security;
drop policy if exists "anon insert" on noeggi.scores;
drop policy if exists "anon read"   on noeggi.scores;
drop policy if exists "anon insert" on noeggi.feedback;
drop policy if exists "anon read"   on noeggi.bonus;
create policy "anon insert" on noeggi.scores   for insert to anon with check (true);
create policy "anon read"   on noeggi.scores   for select to anon using (true);
create policy "anon insert" on noeggi.feedback for insert to anon with check (true);
create policy "anon read"   on noeggi.bonus    for select to anon using (true);

create or replace function noeggi.player_get(tok uuid)
returns table(name text, collected jsonb)
language sql security definer set search_path = noeggi as
$$ select name, collected from noeggi.players where token = tok $$;

create or replace function noeggi.player_upsert(tok uuid, pname text, pcollected jsonb, pfp text)
returns void language sql security definer set search_path = noeggi as
$$ insert into noeggi.players(token, name, collected, fp) values (tok, pname, pcollected, pfp)
   on conflict (token) do update set name = excluded.name,
     collected = excluded.collected, fp = excluded.fp, updated_at = now() $$;

create or replace function noeggi.player_by_fp(pfp text)
returns table(token uuid, name text, collected jsonb)
language sql security definer set search_path = noeggi as
$$ select token, name, collected from noeggi.players
   where fp = pfp and length(coalesce(pfp,'')) > 8
     and (select count(*) from noeggi.players p2 where p2.fp = pfp) = 1 $$;

create or replace function noeggi.player_by_name(pname text)
returns table(token uuid, name text, collected jsonb)
language sql security definer set search_path = noeggi as
$$ select token, name, collected from noeggi.players
   where lower(name) = lower(pname)
     and (select count(*) from noeggi.players p2 where lower(p2.name) = lower(pname)) = 1 $$;

create or replace function noeggi.feedback_list()
returns table(created_at timestamptz, qid text, claim text, name text, lang text)
language sql security definer set search_path = noeggi as
$$ select f.created_at, f.qid, f.claim, f.name, f.lang
   from noeggi.feedback f order by f.created_at desc limit 200 $$;

revoke all on all functions in schema noeggi from public, anon, authenticated;
grant execute on function noeggi.player_get(uuid) to anon;
grant execute on function noeggi.player_upsert(uuid, text, jsonb, text) to anon;
grant execute on function noeggi.player_by_fp(text) to anon;
grant execute on function noeggi.player_by_name(text) to anon;
grant execute on function noeggi.feedback_list() to anon;

